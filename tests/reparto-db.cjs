const { PGlite } = require('@electric-sql/pglite');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated;
    create schema auth;
    create table auth.users(id uuid primary key);
    insert into auth.users values ('00000000-0000-0000-0000-000000000001');
    create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('test.uid',true),'')::uuid $$;
    select set_config('test.uid','00000000-0000-0000-0000-000000000001',false);
    create table pedidos(id text primary key, estado text default 'Pendiente', retiro boolean default false, eliminado_en timestamptz);
    create table pedido_items(id bigint primary key,pedido_id text references pedidos(id),producto text,cantidad numeric);
    create publication supabase_realtime;
    create schema storage;
    create table storage.buckets(id text primary key,name text,public boolean);
    create table storage.objects(bucket_id text);
  `);
  await db.exec(fs.readFileSync('supabase/migrations/20261113_preparacion.sql','utf8'));
  await db.exec(fs.readFileSync('supabase/migrations/20261116_reparto_en_vivo.sql','utf8'));
  await db.exec(`insert into pedidos(id) values ('p1'),('p2');
    insert into pedido_items values (1,'p1','Queso',2),(2,'p2','Pan',3);
    insert into prep_productos(nombre,se_pesa) values ('Queso',true);`);
  const move = (id,to,version,who='Oscar') => db.query('select * from prep_mover($1,$2,$3,$4)',[id,to,version,who]);
  assert.equal((await move('p1','por_preparar',0)).rows[0].version,1);
  await assert.rejects(move('p1','por_preparar',0),/Otro compañero/);
  await assert.rejects(move('p1','listo',1),/Movimiento/);
  await move('p1','preparando',1,'Mateo');
  await assert.rejects(move('p1','listo',2,'Mateo'),/Revisá los productos/);
  await db.exec('insert into prep_items(item_id,separado,peso) values (1,true,2.1)');
  await assert.rejects(move('p1','listo',2,'Mateo'),/Revisá los productos/);
  await db.exec("update prep_items set foto='p1/foto.jpg' where item_id=1");
  await move('p1','listo',2,'Mateo');
  assert.equal((await db.query("select estado from pedidos where id='p1'")).rows[0].estado,'Pendiente');
  await move('p1','preparando',3,'Mateo');
  await db.exec('update prep_items set falta=true,enviado=3 where item_id=1');
  await assert.rejects(move('p1','listo',4,'Mateo'),/Revisá los productos/);
  await db.exec('update prep_items set enviado=0,peso=null,foto=null where item_id=1');
  await move('p1','listo',4,'Mateo');
  await move('p2','por_preparar',0);
  await move('p2','pendiente',1);
  assert.equal((await move('p2','por_preparar',2)).rows[0].version,3);
  await db.exec("update pedidos set estado='Despachado' where id='p2'");
  await assert.rejects(move('p2','preparando',3),/ya no está disponible/);
  await db.exec("select set_config('test.uid','',false)");
  await assert.rejects(move('p1','preparando',5),/Iniciá sesión/);
  assert.equal((await db.query("select count(*)::int as n from pg_publication_tables where pubname='supabase_realtime'")).rows[0].n,6);
  await db.close();
  console.log('OK: transiciones, concurrencia, faltantes, peso/foto, sin despacho y publicación Realtime.');
})().catch(e => {console.error(e); process.exitCode=1;});
